/* Файлы сборки (/_nuxt/…) отдаёт раздача статики; сюда попадает только то, чего в сборке нет, — обычно старый кусок кода
   у вкладки, открытой до обновления сайта. Без этого маршрута на такой адрес ушла бы страница приложения с кэшем на год
   (правило для /_nuxt), и браузер навсегда запомнил бы HTML вместо скрипта. Честный 404 без кэша: Nuxt увидит ошибку
   загрузки куска и сам перезагрузит страницу с новой сборкой */
export default defineEventHandler(event => {
  setResponseHeader(event, 'cache-control', 'no-store')
  throw createError({ statusCode: 404, statusMessage: 'Нет такого файла сборки' })
})
